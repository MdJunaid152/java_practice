package com.Methods;

public class With_VS_WithoutMethods {

	public static void main(String[] args) {
		// This is without methods
		System.out.println("Welcome to Java World ");
		System.out.println("Java Is Simple ");
		welcome();
	}
	
	//This is with method
	static void welcome() {
		System.out.println("Have a nice day ");
		System.out.println("Practice makes man perfect");
	}

}
